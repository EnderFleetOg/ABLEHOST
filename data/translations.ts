// Adapt translated string deterministic rules based on the chosen sub-dialect style (urban, modern, visual, simplified, tactile etc.)
export const adaptToDialect = (text: string, code: string): string => {
  if (!code) return text;
  const parts = code.split('-');
  const varietyType = parts[1] || 'standard';

  switch (varietyType.toLowerCase()) {
    case 'assistive':
      return `[🔊 Assistive] ${text}`;
    case 'visual':
    case 'visual-text':
      return `👁️ ${text}`;
    case 'braille':
    case 'braille-ready':
      return `⠆ [Tactile] ${text} (⠿)`;
    case 'rural':
      return `${text} 🌱`;
    case 'metro':
      return `${text} ⚡`;
    case 'professional':
      return `👔 ${text}`;
    case 'youth':
    case 'youth-sync':
      return `${text} ✨`;
    case 'traditional':
      return `📜 ${text}`;
    case 'modern':
    case 'modern-slang':
      return `${text} 🔥`;
    default:
      return text;
  }
};
